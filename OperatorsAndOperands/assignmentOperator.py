# assignment operator
# The assignment operator (=) is used to assign a value to a variable. It takes the value on the right-hand side and assigns it to the variable on the left-hand side. For example:
x = 5  # assigns the value 5 to the variable x
print(x)  # prints the value of x, which is 5
print(x + 2)  # prints the result of x + 2, which is 7  
print(x * 3)  # prints the result of x * 3, which is 15
print(x - 1)  # prints the result of x - 1, which is 4
print(x / 2)  # prints the result of x / 2, which is 2.5
print(x ** 2)  # prints the result of x raised to the power of 2, which is 25
print(x // 2)  # prints the result of x floor divided by 2, which is 2
print(x % 2)  # prints the remainder of x divided by 2, which is 1
print(x == 5)  # prints True, since x is equal to 5
print(x != 5)  # prints False, since x is equal to 5
print(x > 3)  # prints True, since x is greater than 3