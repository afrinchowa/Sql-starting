# Membership Operator in Python is used to test whether a value or variable is found in a sequence (string, list, tuple, set, and dictionary).
# The membership operators in Python are:
# in: Returns True if a value is found in the specified sequence, otherwise returns False.
# not in: Returns True if a value is not found in the specified sequence, otherwise returns False.

a ="Hello"
print("H" in a)  # True
print("h" in a)  # False
print("ell" in a)  # True
print("world" not in a)  # True